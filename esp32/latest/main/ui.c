static void update_state_screen(const app_state_snapshot_t *state)
{
    char text[128];
    set_icon_online_state(s_widgets.lan, state->wifi_connected);
    set_icon_online_state(s_widgets.mac, state->hosts[HOST_MAC].online);
    set_icon_online_state(s_widgets.windows, state->hosts[HOST_WINDOWS].online);

    const host_id_t visible_host = state->display_target;
    const host_status_t *host = &state->hosts[visible_host];
    label_set_text_if_changed(s_widgets.active_host,
                              visible_host == HOST_MAC ? "MAC" : "WIN");
    if (host->temperature_valid) {
        snprintf(text, sizeof(text), "%d", (int)host->cpu_temperature_c);
        label_set_text_if_changed(s_widgets.cpu, text);
    } else label_set_text_if_changed(s_widgets.cpu, "--");
    int memory_segments = 0;
    if (host->memory_valid) {
        const int memory_percent = (int)host->memory_percent;
        snprintf(text, sizeof(text), "%d%%", memory_percent);
        label_set_text_if_changed(s_widgets.memory, text);
        memory_segments = memory_percent > 0 ? (memory_percent + 4) / 5 : 0;
    } else {
        label_set_text_if_changed(s_widgets.memory, "--%");
    }
    if (memory_segments > 20) memory_segments = 20;
    for (int i = 0; i < 20; ++i) {
        set_bg_color_if_changed(s_widgets.memory_segments[i],
                                i < memory_segments ? 0x111111 : 0xffffff);
    }

    static const char *dashboard_titles[] = { "SYSTEM", "WEATHER", "MARKETS" };
    const uint8_t dashboard_page = state->data_window_index < 3 ? state->data_window_index : 0;
    label_set_text_if_changed(s_widgets.dashboard_title, dashboard_titles[dashboard_page]);
    for (int i = 0; i < 3; ++i) {
        if (i == dashboard_page) lv_obj_clear_flag(s_widgets.dashboard_pages[i], LV_OBJ_FLAG_HIDDEN);
        else lv_obj_add_flag(s_widgets.dashboard_pages[i], LV_OBJ_FLAG_HIDDEN);
    }

    static const char *modes[] = { "MANUAL", "STANDARD", "SILENT", "TURBO" };
    label_set_text_if_changed(s_widgets.cooler_mode, modes[state->thermal_mode]);
    if (state->thermal_mode == THERMAL_MANUAL) {
        label_set_text_if_changed(s_widgets.cooler_target, "--");
    } else {
        snprintf(text, sizeof(text), "%d", state->thermal_targets_c[state->thermal_mode]);
        label_set_text_if_changed(s_widgets.cooler_target, text);
    }
    if (state->cooler_state == COOLER_INITIALIZING) {
        label_set_text_if_changed(s_widgets.cooler_level, "...");
    } else if (state->cooler_state == COOLER_ERROR) {
        label_set_text_if_changed(s_widgets.cooler_level, "!");
    } else if (state->cooler_state == COOLER_OFF || state->cooler_level == 0) {
        label_set_text_if_changed(s_widgets.cooler_level, "-");
    } else {
        snprintf(text, sizeof(text), "%u", state->cooler_level);
        label_set_text_if_changed(s_widgets.cooler_level, text);
    }

    const bool kvm_error = state->kvm_phase == KVM_ERROR ||
                           state->command_error[0] != '\0';
    const bool ready = state->wifi_connected && host->online && !kvm_error &&
                       (state->kvm_phase == KVM_IDLE ||
                        state->kvm_phase == KVM_DISABLED_UNCONFIRMED_TIMING);
    if (kvm_error) {
        label_set_text_if_changed(s_widgets.health_mark, "X");
        set_text_color_if_changed(s_widgets.health_mark, 0xb73832);
        label_set_text_if_changed(s_widgets.health_text, "ERROR");
    } else if (ready) {
        label_set_text_if_changed(s_widgets.health_mark, "OK");
        set_text_color_if_changed(s_widgets.health_mark, 0x3f8f4d);
        label_set_text_if_changed(s_widgets.health_text, "READY");
    } else if (!state->wifi_connected || !host->online) {
        label_set_text_if_changed(s_widgets.health_mark, "...");
        set_text_color_if_changed(s_widgets.health_mark, 0xd17d22);
        label_set_text_if_changed(s_widgets.health_text, "WAITING");
    } else {
        label_set_text_if_changed(s_widgets.health_mark, ">");
        set_text_color_if_changed(s_widgets.health_mark, 0x376ca8);
        label_set_text_if_changed(s_widgets.health_text, phase_text(state->kvm_phase));
    }
    snprintf(text, sizeof(text), "IP %s", state->ip_address);
    label_set_text_if_changed(s_widgets.network, text);
    snprintf(text, sizeof(text), "DATA %s%s",
             state->dashboard_valid ? (state->dashboard_source == HOST_WINDOWS ? "WINDOWS" : "MAC") : "NONE",
             state->dashboard_stale ? " (STALE)" : "");
    label_set_text_if_changed(s_widgets.connections, text);
    if (state->command_error[0] != '\0') {
        snprintf(text, sizeof(text), "ERROR: %s", state->command_error);
        label_set_text_if_changed(s_widgets.error, text);
    } else if (state->kvm_phase == KVM_ERROR) {
        snprintf(text, sizeof(text), "ERROR: %s", state->last_message);
        label_set_text_if_changed(s_widgets.error, text);
    } else {
        label_set_text_if_changed(s_widgets.error,
            state->dashboard_error[0] != '\0' ? state->dashboard_error : "NO ERRORS");
    }

    static uint64_t rendered_dashboard_revision = UINT64_MAX;
    if (state->dashboard_revision != rendered_dashboard_revision) {
        rendered_dashboard_revision = state->dashboard_revision;
        if (state->weather.valid) {
            label_set_text_if_changed(s_widgets.weather_city, state->weather.city_name);
            snprintf(text, sizeof(text), "%d", state->weather.current.temperature_c);
            label_set_text_if_changed(s_widgets.weather_temperature, text);
            snprintf(text, sizeof(text), "%d/%d", state->weather.current.high_c,
                     state->weather.current.low_c);
            label_set_text_if_changed(s_widgets.weather_high_low, text);
            draw_weather_icon(s_widgets.weather_current_icon,
                              state->weather.current.weather_code,
                              state->weather.current.is_day);
            for (int i = 0; i < APP_WEATHER_DAILY_COUNT; ++i) {
                label_set_text_if_changed(s_widgets.weather_daily_day[i], state->weather.daily[i].day);
                snprintf(text, sizeof(text), "%d", state->weather.daily[i].high_c);
                label_set_text_if_changed(s_widgets.weather_daily_value[i], text);
                draw_weather_icon(s_widgets.weather_daily_icon[i],
                                  state->weather.daily[i].weather_code, true);
            }
            for (int i = 0; i < APP_WEATHER_HOURLY_COUNT; ++i) {
                snprintf(text, sizeof(text), "%02u", state->weather.hourly[i].hour);
                label_set_text_if_changed(s_widgets.weather_hour[i], text);
                snprintf(text, sizeof(text), "%d", state->weather.hourly[i].temperature_c);
                label_set_text_if_changed(s_widgets.weather_hour_temperature[i], text);
                draw_weather_icon(s_widgets.weather_hour_icon[i],
                                  state->weather.hourly[i].weather_code,
                                  state->weather.hourly[i].is_day);
            }
        } else {
            label_set_text_if_changed(s_widgets.weather_city, "NO WEATHER DATA");
        }
        if (state->markets.valid) {
            const market_quote_t quotes[] = { state->markets.btc_usdt,
                                              state->markets.doge_usdt,
                                              state->markets.usd_cny };
            for (int i = 0; i < 3; ++i) {
                if (i == 0) snprintf(text, sizeof(text), "%.0f", quotes[i].price);
                else if (i == 1) snprintf(text, sizeof(text), "%.5f", quotes[i].price);
                else snprintf(text, sizeof(text), "%.4f", quotes[i].price);
                label_set_text_if_changed(s_widgets.market_price[i], text);
                snprintf(text, sizeof(text), "%+.2f%%", quotes[i].change_percent);
                label_set_text_if_changed(s_widgets.market_change[i], text);
                set_text_color_if_changed(s_widgets.market_change[i],
                    quotes[i].change_percent >= 0 ? 0x3f8f4d : 0xb73832);
            }
        }
    }
}

static int64_t update_clock_screen(void)
{
    const time_t now = time(NULL);
    if (now < 1700000000) {
        label_set_text_if_changed(s_widgets.clock, "--:--");
        return 1000;
    }
    struct tm local_time;
    localtime_r(&now, &local_time);
    char text[6];
    strftime(text, sizeof(text), "%H:%M", &local_time);
    label_set_text_if_changed(s_widgets.clock, text);
    return (int64_t)(60 - local_time.tm_sec) * 1000;
}

static void ui_task(void *argument)
{
    (void)argument;
    setenv("TZ", "CST-8", 1);
    tzset();
    lv_init();
    lv_tick_set_cb(tick_ms);
    lv_display_t *display = NULL;
    esp_err_t result = lcd_lvgl_init(&display);
    if (result != ESP_OK) {
        ESP_LOGE(TAG, "Display initialization failed: %s", esp_err_to_name(result));
        vTaskDelete(NULL);
        return;
    }
    (void)display;
    lv_obj_t *boot_status = create_boot_screen();
    /* Flush the lightweight boot screen before enabling its backlight. */
    (void)lv_timer_handler();
    hardware_set_backlight(true);
    app_state_set_backlight(s_state, true);
    s_ready = true;

    uint64_t rendered_revision = 0;
    int64_t next_clock_refresh_ms = 0;
    bool main_screen_visible = false;
    for (;;) {
        const int64_t now_ms = esp_timer_get_time() / 1000;
        ui_command_t command;
        while (xQueueReceive(s_commands, &command, 0) == pdTRUE) {
            if (command.type == UI_COMMAND_BOOT_STATUS && !main_screen_visible) {
                lv_label_set_text(boot_status, command.text);
            } else if (command.type == UI_COMMAND_SHOW_MAIN && !main_screen_visible) {
                create_screen();
                main_screen_visible = true;
                rendered_revision = UINT64_MAX;
                next_clock_refresh_ms = 0;
            }
        }
        app_state_snapshot_t snapshot;
        if (main_screen_visible && app_state_get_snapshot(s_state, &snapshot)) {
            if (snapshot.revision != rendered_revision) {
                update_state_screen(&snapshot);
                rendered_revision = snapshot.revision;
            }
            if (now_ms >= next_clock_refresh_ms) {
                next_clock_refresh_ms = now_ms + update_clock_screen();
            }
        }
        uint32_t wait_ms = lv_timer_handler();
        if (wait_ms < 5) wait_ms = 5;
        if (wait_ms > 20) wait_ms = 20;
        vTaskDelay(pdMS_TO_TICKS(wait_ms));
    }
}

esp_err_t ui_start(app_state_t *state)
{
    if (state == NULL) return ESP_ERR_INVALID_ARG;
    if (s_task != NULL) return ESP_OK;
    s_state = state;
    s_ready = false;
    s_commands = xQueueCreate(4, sizeof(ui_command_t));
    if (s_commands == NULL) return ESP_ERR_NO_MEM;
    if (xTaskCreate(ui_task, "lvgl_ui", 8192, NULL, 5, &s_task) != pdPASS) {
        vQueueDelete(s_commands);
        s_commands = NULL;
        s_task = NULL;
        return ESP_ERR_NO_MEM;
    }
    return ESP_OK;
}

bool ui_wait_ready(uint32_t timeout_ms)
{
    const TickType_t deadline = xTaskGetTickCount() + pdMS_TO_TICKS(timeout_ms);
    while (!s_ready && xTaskGetTickCount() < deadline) {
        vTaskDelay(pdMS_TO_TICKS(10));
    }
    return s_ready;
}

esp_err_t ui_set_boot_status(const char *status)
{
    if (s_commands == NULL || status == NULL || status[0] == '\0') {
        return ESP_ERR_INVALID_STATE;
    }
    ui_command_t command = { .type = UI_COMMAND_BOOT_STATUS };
    snprintf(command.text, sizeof(command.text), "%s", status);
    return xQueueSend(s_commands, &command, pdMS_TO_TICKS(50)) == pdTRUE
        ? ESP_OK : ESP_ERR_TIMEOUT;
}

esp_err_t ui_show_main_screen(void)
{
    if (s_commands == NULL) return ESP_ERR_INVALID_STATE;
    const ui_command_t command = { .type = UI_COMMAND_SHOW_MAIN };
    return xQueueSend(s_commands, &command, pdMS_TO_TICKS(50)) == pdTRUE
        ? ESP_OK : ESP_ERR_TIMEOUT;
}
