typedef enum { WEATHER_SUN, WEATHER_CLOUD, WEATHER_RAIN, WEATHER_SNOW,
               WEATHER_THUNDER, WEATHER_FOG } weather_icon_kind_t;

static weather_icon_kind_t weather_icon_kind(uint16_t code)
{
    if ((code >= 300 && code <= 399) || (code >= 51 && code <= 82)) {
        return code == 302 || code == 303 || code == 304 ? WEATHER_THUNDER : WEATHER_RAIN;
    }
    if ((code >= 400 && code <= 499) || (code >= 71 && code <= 86)) return WEATHER_SNOW;
    if ((code >= 500 && code <= 515) || (code >= 45 && code <= 48)) return WEATHER_FOG;
    if (code >= 95 && code <= 99) return WEATHER_THUNDER;
    if ((code >= 101 && code <= 104) || code == 2 || code == 3) return WEATHER_CLOUD;
    return WEATHER_SUN;
}

static void draw_weather_icon(lv_obj_t *holder, uint16_t code, bool is_day)
{
    lv_obj_clean(holder);
    const int size = lv_obj_get_width(holder);
    const int s = size >= 22 ? 3 : 2;
    const weather_icon_kind_t kind = weather_icon_kind(code);
    if (kind == WEATHER_SUN) {
        const uint32_t color = is_day ? 0xf0b429 : 0x5a68a5;
        pixel(holder, 2*s, 1*s, 3*s, 1*s, color);
        pixel(holder, 1*s, 2*s, 5*s, 3*s, color);
        pixel(holder, 2*s, 5*s, 3*s, 1*s, color);
        return;
    }
    if (kind == WEATHER_THUNDER) {
        pixel(holder, 1*s, 1*s, 5*s, 3*s, 0x778899);
        pixel(holder, 3*s, 4*s, 2*s, 1*s, 0xf0b429);
        pixel(holder, 2*s, 5*s, 2*s, 2*s, 0xf0b429);
        return;
    }
    if (kind == WEATHER_FOG) {
        pixel(holder, 1*s, 2*s, 5*s, 1*s, 0x9aa3a8);
        pixel(holder, 2*s, 4*s, 5*s, 1*s, 0x9aa3a8);
        pixel(holder, 1*s, 6*s, 4*s, 1*s, 0x9aa3a8);
        return;
    }
    pixel(holder, 1*s, 1*s, 4*s, 1*s, 0x7c93a5);
    pixel(holder, 0*s, 2*s, 6*s, 2*s, 0x7c93a5);
    if (kind == WEATHER_CLOUD) return;
    const uint32_t drop = kind == WEATHER_SNOW ? 0xb9d9ef : 0x2e86c1;
    pixel(holder, 1*s, 5*s, 1*s, 1*s, drop);
    pixel(holder, 3*s, 4*s, 1*s, 1*s, drop);
    pixel(holder, 5*s, 5*s, 1*s, 1*s, drop);
}

